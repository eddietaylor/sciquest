@dataclass(frozen=True)
class StudyConfig:
    model: str = "gpt-6.1-sol"
    reasoning_effort: str = "high"
    budget: int = 12
    max_queries: int = 6
    timeout: int = 120
    repeats: int = 1
    concurrency: int = 4

    def __post_init__(self):
        if not isinstance(self.model, str) or not self.model.strip():
            raise ValueError("An explicit model is required")
        if self.reasoning_effort not in ("low", "medium", "high", "xhigh"):
            raise ValueError("Unknown reasoning setting")
        for key, limit in (
            ("budget", 1000),
            ("max_queries", 100),
            ("timeout", 600),
            ("repeats", 100),
            ("concurrency", 4),
        ):
            if (
                type(getattr(self, key)) is not int
                or not 1 <= getattr(self, key) <= limit
            ):
                raise ValueError("Invalid study limit: " + key)


def _read(path):
    return json.loads(Path(path).read_text())


def _write_new(path, value):
    with Path(path).open("x") as f:
        f.write(json.dumps(value, indent=2) + "\n")


def method_prompts():
    registry = MethodRegistry.default()
    result = {}
    for policy in POLICIES:
        p = registry.get(policy)
        result[policy] = "\n".join(
            [
                "Assigned inquiry policy: " + p.display_name,
                p.description,
                "Hypotheses: " + "; ".join(p.hypothesis_generation_rules),
                "Experiment design: " + "; ".join(p.experiment_design_rules),
                "Evidence: " + "; ".join(p.evidence_evaluation_rules),
                "Validation: " + "; ".join(p.validation_rules),
                "Next step: " + "; ".join(p.next_step_policy),
            ]
        )
    return result


def freeze_study(
    path: Path, config=StudyConfig(), binary="codex", *, assisted=False
) -> dict:
    """Create a new immutable protocol and private matched-world allocation."""
    if not assisted:
        raise ValueError(
            "This legacy study supplies model equations and inference. Explicit assisted=True is required; it is not blind discovery."
        )
    backend = describe_backend(binary)
    path = Path(path).resolve()
    path.mkdir(parents=True, exist_ok=False, mode=0o700)
    blocks = []
    for case, replicate in itertools.product(SCENARIOS, range(config.repeats)):
        seed = secrets.randbelow(2**32 - 10000) + 10000
        blocks.append(
            dict(
                id=f"b{len(blocks):03d}", scenario=case, replicate=replicate, seed=seed
            )
        )
    order_seed = secrets.randbits(64)
    rng = random.Random(order_seed)
    order = [(b["id"], policy) for b in blocks for policy in POLICIES]
    rng.shuffle(order)
    protocol = dict(
        version=VERSION,
        frozen_at=utc_now(),
        **asdict(config),
        scheduling="Randomized submission order, bounded concurrent campaigns; model timing and completion order can vary.",
        max_model_calls=config.max_queries + 1,
        policies=list(POLICIES),
        scenarios=list(SCENARIOS),
        campaigns=len(order),
        backend=backend,
        runtime=runtime_manifest(),
        common_prompt=COMMON_PROMPT,
        method_prompts=method_prompts(),
        response_schema=RESPONSE_SCHEMA,
        blocks=[
            {k: v for k, v in b.items() if k != "seed"}
            | {"seed_commitment": content_hash([VERSION, b["id"], b["seed"]])}
            for b in blocks
        ],
        order=[dict(block=b, policy=p) for b, p in order],
        primary="Mean family Brier with failed/incomplete campaigns assigned 2, paired against standard_empirical by independent world block; descriptive at this sample size.",
        secondary=[
            "completion_rate",
            "completed_family_brier",
            "correct_identifiability_abstention",
            "correct_model_inadequacy_abstention",
            "interpolation_demand_rmse",
            "extrapolation_demand_rmse",
            "mean_interval_score_90",
            "predictive_interval_coverage_90",
            "policy_value",
            "unconstrained_grid_regret",
            "constraint_violation_rate",
            "cost_spent",
            "model_usage",
        ],
        failure_policy="No supervisor-initiated retries, repairs or replacement seeds. Preserve all attempts. Interrupted runs count as failures unless a completed native result already exists. Never change this version after observing outcomes.",
        resources="Equal query/cost/model-call caps, reasoning setting, model slug and per-call timeout. Tokens are measured outcomes, not a hard token-equalized experiment. One model call means one isolated CLI invocation/turn; client transport recovery is not separately metered. CLI can overshoot a wall deadline before termination; no exact server token cap is claimed.",
        analysis="No significance tests, philosophy ranking or superiority claim from this small first study. Report every block, paired differences and failures. Calibration needs repeated independent campaigns; 60 prediction rows are not 60 independent worlds.",
        limitations="LLM experimental-design/decision study with shared finite Bayesian inference and fixed forecasts, not free-form discovery. Assigned operational instructions are treatments, not exhaustive philosophies. Model slug is pinned; provider weights and system instructions are not immutable snapshots.",
    )
    digest = content_hash(protocol)
    _write_new(path / "protocol.json", protocol)
    (path / "protocol.sha256").write_text(digest + "\n")
    (path / "protocol.json").chmod(0o444)
    _write_new(
        path / "allocation.private.json",
        dict(protocol_hash=digest, blocks=blocks, order_seed=order_seed),
    )
    (path / "allocation.private.json").chmod(0o600)
    return dict(path=str(path), protocol_hash=digest, campaigns=len(order))


def load_study(path: Path):
    path = Path(path).resolve()
    spec = _read(path / "protocol.json")
    digest = content_hash(spec)
    allocation = _read(path / "allocation.private.json")
    if (
        digest != (path / "protocol.sha256").read_text().strip()
        or digest != allocation["protocol_hash"]
    ):
        raise ValueError("Frozen study protocol changed")
    if (
        spec["version"] != VERSION
        or spec["common_prompt"] != COMMON_PROMPT
        or spec["response_schema"] != RESPONSE_SCHEMA
        or spec["method_prompts"] != method_prompts()
    ):
        raise ValueError("Study implementation or prompts differ from frozen version")
    if spec["runtime"]["fingerprint"] != runtime_manifest()["fingerprint"]:
        raise ValueError(
            "Frozen study runtime changed; preserve this study and create a new version"
        )
    for public, private in zip(spec["blocks"], allocation["blocks"]):
        if any(public[k] != private[k] for k in ("id", "scenario", "replicate")):
            raise ValueError("Public and private study blocks differ")
        if public["seed_commitment"] != content_hash(
            [VERSION, private["id"], private["seed"]]
        ):
            raise ValueError("Study world allocation changed")
    if len(spec["blocks"]) != len(allocation["blocks"]):
        raise ValueError("Study block allocation mismatch")
    expected_order = {(b["id"], p) for b in spec["blocks"] for p in POLICIES}
    actual_order = [(item["block"], item["policy"]) for item in spec["order"]]
    if len(actual_order) != len(expected_order) or set(actual_order) != expected_order:
        raise ValueError("Study order must include every block and arm exactly once")
    return spec, allocation, digest


def action_distribution(view, action, models):
    """Conditional prospective measurement distributions, including paired audits."""
    public = view["contract"]
    design, cost = normalize_action(action, public, view["history"])
    endog = public["historical_assignment"] == "endogenous"
    if design["kind"] == "measure":
        origin = next(
            r["observation"]
            for r in view["history"]
            if r["observation"]["id"] == design["observation_id"]
        )
        audits = [
            r["observation"]
            for r in view["history"]
            if r["observation"].get("paired_with") == origin["id"]
        ]
        us = (
            [int(round(4 * (origin["price"] - 1)))]
            if endog and origin["kind"] == "observe"
            else [-1, 0, 1]
        )
        distributions = []
        for particle in models:
            values = [
                demand(particle["model"], origin["price"], origin["context"], u, endog)
                for u in us
            ]
            logs = [
                _log_normal(
                    origin["value"], min(origin["capacity"], v), origin["sigma"]
                )
                + math.fsum(_log_normal(a["value"], v, a["sigma"]) for a in audits)
                for v in values
            ]
            norm = _log_sum(logs)
            distributions.append(list(zip(values, [math.exp(v - norm) for v in logs])))
        return distributions, 1, cost
    sigma = (
        public["precise_sensor_sigma"]
        if design["precision"] == "precise"
        else public["sensor_sigma"]
    )
    distributions = []
    for particle in models:
        m = particle["model"]
        if design["kind"] == "observe":
            cap = public["historical_capacity"]
            pairs = (
                [(1 + u / 4, u) for u in (-1, 0, 1)]
                if endog
                else list(itertools.product(public["prices"], (-1, 0, 1)))
            )
            values = [
                min(cap, demand(m, p, design["context"], u, endog)) for p, u in pairs
            ]
        else:
            values = components(
                m, design["price"], design["context"], design["capacity"], endog
            )
        distributions.append([(v, 1 / len(values)) for v in values])
    return distributions, sigma, cost


def available_actions(view):
    actions = [
        dict(kind="observe", context=x, precision=s)
        for x, s in itertools.product((-1, 0, 1), ("standard", "precise"))
    ]
    if view["contract"]["interventions_available"]:
        actions += [
            dict(kind="intervene", price=p, context=x, capacity=c, precision=s)
            for p, x, c, s in itertools.product(
                (0.5, 1, 1.5), (-1, 1), (60, 180), ("standard", "precise")
            )
        ]
    for r in view["history"]:
        if r["observation"]["kind"] != "measure":
            actions += [
                dict(kind=k, observation_id=r["observation"]["id"])
                for k in ("replicate", "measure")
            ]
    return {
        f"a{i:03d}": a
        for i, a in enumerate(actions)
        if normalize_action(a, view["contract"], view["history"])[1]
        <= view["remaining"]
    }


def measurement_plan(view, action, models, weights, reason):
    distributions, sigma, _ = action_distribution(view, action, models)
    means = [math.fsum(v * p for v, p in d) for d in distributions]
    threshold = (min(means) + max(means)) / 2
    likelihood = [
        math.fsum(w * event_probability(threshold, [v], sigma) for v, w in d)
        for d in distributions
    ]
    ids = [f"particle_{i:02d}" for i in range(len(models))]
    kind = action["kind"]
    return dict(
        question="Which declared predictive particles explain this chosen measurement?",
        hypothesis="The new scalar measurement is at most the preregistered threshold.",
        scope="One adaptive exploratory demand query, with shared numerical assistance.",
        assumptions="Public structural nuisance and Gaussian sensor models; finite nonexhaustive particle approximation. Audits condition on the same unit's earlier sales and audits.",
        data_access="Public discovery contract and this campaign's earlier observations only.",
        stopping_rule="One measurement; later scientific stopping remains an LLM decision subject to frozen resource caps.",
        action={
            "replicate": "replication",
            "measure": "measurement",
            "observe": "data_acquisition",
            "intervene": "rival_test",
        }[kind],
        confirmatory_status="exploratory",
        rationale=reason,
        predictions=[
            dict(id="p1", metric="observation", operator="<=", threshold=threshold)
        ],
        rivals=[
            dict(
                id=k,
                claim="Fixed predictive particle " + canonical_json(m["model"]),
                predictions={"p1": v},
            )
            for k, m, v in zip(ids, models, means)
        ],
        discriminating_prediction_id="p1",
        belief_model=dict(
            prediction_id="p1",
            prior=dict(zip(ids, weights)),
            likelihood={
                k: dict(
                    supported=bounded_probability(p),
                    contradicted=1 - bounded_probability(p),
                )
                for k, p in zip(ids, likelihood)
            },
            assumptions="Conditional predictive CDF under the shared finite-particle model given complete raw history once from original prior. The recorded binary update is separate from the full-value inference; no chained binary-prior claim.",
        ),
        severe_test=dict(
            prediction_id="p1",
            failure_action="revise",
            auxiliary_assumptions=[
                "Stable sensor calibration, nuisance distribution and structural world."
            ],
            diagnostic_rationale="The LLM's registered choice and rationale target a possible inadequacy; numerical assistance does not certify severity. "
            + reason,
        ),
    )


def scientist_context(view, spec, models, weights, choices):
    probs = family_probabilities(models, weights)
    estimates = {}
    for f in FAMILIES:
        if probs[f] > 0:
            estimates[f] = {
                k: math.fsum(
                    w * m["model"][k] / probs[f]
                    for m, w in zip(models, weights)
                    if m["label"] == f
                )
                for k in ("baseline", "context_effect", "sensitivity")
            }
    actions = []
    for identity, action in choices.items():
        distributions, sigma, cost = action_distribution(view, action, models)
        means = [math.fsum(v * p for v, p in d) for d in distributions]
        family_means = {}
        for f in FAMILIES:
            members = [i for i, m in enumerate(models) if m["label"] == f]
            mass = probs[f]
            family_means[f] = round(
                math.fsum(weights[i] * means[i] / mass for i in members)
                if mass
                else math.fsum(means[i] for i in members) / len(members),
                4,
            )
        actions.append(
            dict(
                id=identity,
                action=action,
                cost=cost,
                sensor_sigma=sigma,
                expected_measurement_by_family=family_means,
            )
        )
    observations = [
        dict(
            observation=r["observation"],
            action=r["action"],
            reason=r["plan"].get("rationale"),
        )
        for r in view["history"]
    ]
    return dict(
        contract=view["contract"],
        observations=observations,
        shared_family_probabilities=probs,
        shared_conditional_parameters=estimates,
        remaining_cost=view["remaining"],
        max_queries=spec["max_queries"],
        queries_used=len(observations),
        available_actions=actions,
        stop_required=len(observations) >= spec["max_queries"] or not choices,
    )


def validate_response(response, choices, stop_required):
    if not isinstance(response, dict) or set(response) != {
        "kind",
        "action_id",
        "reason",
        "decision",
    }:
        raise ValueError("Unexpected scientist response fields")
    if (
        not isinstance(response["reason"], str)
        or not response["reason"].strip()
        or len(response["reason"]) > 8192
    ):
        raise ValueError("A bounded scientific rationale is required")
    if response["kind"] == "query":
        if (
            stop_required
            or response["decision"] is not None
            or not isinstance(response["action_id"], str)
            or response["action_id"] not in choices
        ):
            raise ValueError(
                "Query is not allowed or does not identify an affordable action"
            )
        return None
    if response["kind"] != "stop" or response["action_id"] is not None:
        raise ValueError("Invalid stopping response")
    decision = response["decision"]
    if not isinstance(decision, dict) or set(decision) != set(
        DECISION_SCHEMA["properties"]
    ):
        raise ValueError("Stopping requires all declared scientific decision fields")
    clean = {k: v for k, v in decision.items() if v is not None}
    return validate_decision(clean)


def _campaign(directory, spec, digest, block, policy, protected_root):
    session = DemandSession.create(
        directory / "session",
        DemandConfig(block["scenario"], block["seed"], spec["budget"]),
        policy,
        assisted=True,
    )
    receipts = []
    outcome = dict(
        block=block["id"],
        policy=policy,
        protocol_hash=digest,
        status="failed",
        primary_family_brier=2.0,
        calls=[],
        error=None,
    )
    try:
        for index in range(spec["max_model_calls"]):
            view = session.view()
            models, weights = infer(view)
            choices = available_actions(view) if index < spec["max_queries"] else {}
            context = scientist_context(view, spec, models, weights, choices)
            prompt = (
                spec["common_prompt"]
                + "\n\n"
                + spec["method_prompts"][policy]
                + "\n\nPUBLIC CONTEXT\n"
                + canonical_json(context)
            )
            receipt = run_call(
                directory / "calls" / f"call-{index + 1:02d}",
                prompt,
                RESPONSE_SCHEMA,
                spec,
                protected_root,
                spec["timeout"],
            )
            receipts.append(receipt)
            if receipt["status"] != "succeeded":
                raise ValueError(receipt.get("error", "Model preparation failed"))
            response = receipt["response"]
            decision = validate_response(response, choices, context["stop_required"])
            with session.transaction() as (c, state):
                session._append(
                    c,
                    dict(
                        type="study_model_call",
                        call=index + 1,
                        response_hash=receipt["response_hash"],
                        prompt_hash=receipt["prompt_hash"],
                        usage=receipt["usage"],
                        reason=response["reason"],
                    ),
                )
            if decision is not None:
                session.stop(decision, session.view()["revision"])
                session.prepare_quest()
                final_view = session.view()
                models, weights = infer(final_view)
                notebook, plan = final_artifacts(
                    final_view, models, weights, directory / "fixed_predictor"
                )
                result = session.finish(notebook, plan)
                proof = session.verify()
                outcome.update(
                    status="completed",
                    primary_family_brier=result["science"]["family_brier"],
                    science=result["science"],
                    decision=final_view["decision"],
                    verification=proof,
                )
                break
            action = choices[response["action_id"]]
            plan = measurement_plan(view, action, models, weights, response["reason"])
            session.query(
                dict(revision=session.view()["revision"], action=action, plan=plan)
            )
        else:
            raise ValueError("Frozen model-call budget exhausted")
    except (ValueError, OSError, RuntimeError, KeyError) as exc:
        outcome["error"] = str(exc)
    outcome["calls"] = [
        {k: v for k, v in r.items() if k != "response"} for r in receipts
    ]
    view = session.view()
    outcome.update(
        cost_spent=view["spent"],
        query_count=len(view["history"]),
        model_calls=len(receipts),
        session_phase=view["phase"],
    )
    _write_new(directory / "result.json", outcome)
    return outcome


def summarize(spec, results, digest):
    arms = {}
    by_pair = {(r["block"], r["policy"]): r for r in results}
    for policy in POLICIES:
        rows = [r for r in results if r["policy"] == policy]
        completed = [r for r in rows if r["status"] == "completed"]
        deltas = [
            r["primary_family_brier"]
            - by_pair[(r["block"], POLICIES[0])]["primary_family_brier"]
            for r in rows
            if (r["block"], POLICIES[0]) in by_pair
        ]
        usage = [c.get("usage") for r in rows for c in r["calls"]]
        arms[policy] = dict(
            attempted=len(rows),
            completed=len(completed),
            failed=len(rows) - len(completed),
            mean_primary_family_brier=math.fsum(r["primary_family_brier"] for r in rows)
            / len(rows)
            if rows
            else None,
            complete_case_family_brier=math.fsum(
                r["science"]["family_brier"] for r in completed
            )
            / len(completed)
            if completed
            else None,
            paired_blocks_vs_empirical=len(deltas),
            mean_paired_brier_difference_vs_empirical=math.fsum(deltas) / len(deltas)
            if deltas
            else None,
            total_model_calls=len(usage),
            usage_complete=all(isinstance(u, dict) for u in usage),
            recorded_input_tokens=sum(u["input_tokens"] for u in usage if u),
            recorded_output_tokens=sum(u["output_tokens"] for u in usage if u),
        )
    return dict(
        protocol_hash=digest,
        expected_campaigns=spec["campaigns"],
        recorded_campaigns=len(results),
        complete=len(results) == spec["campaigns"],
        arms=arms,
        results=results,
        scope=spec["analysis"],
        primary_definition=spec["primary"],
        resources=spec["resources"],
    )


def _recover_campaign(directory, item, digest):
    calls = []
    for call in sorted((directory / "calls").glob("call-*")):
        receipt_file = call / "receipt.json"
        if receipt_file.exists():
            receipt = _read(receipt_file)
        else:
            receipt = dict(
                status="interrupted",
                usage=None,
                recovered_without_receipt=True,
                prompt_hash=content_hash((call / "prompt.txt").read_text()),
                schema_hash=content_hash(_read(call / "schema.json")),
            )
            if (call / "trace.jsonl").exists():
                receipt["trace_sha256"] = file_hash(call / "trace.jsonl")
                try:
                    receipt["usage"] = parse_events((call / "trace.jsonl").read_text())[
                        "usage"
                    ]
                except ValueError:
                    pass
            _write_new(receipt_file, receipt)
        calls.append({k: v for k, v in receipt.items() if k != "response"})
    result = dict(
        **item,
        protocol_hash=digest,
        status="interrupted",
        primary_family_brier=2.0,
        calls=calls,
        model_calls=len(calls),
        error="Interrupted campaign preserved; no replacement or new model calls.",
    )
    if (directory / "session/.demand/state.sqlite3").is_file():
        session = DemandSession(directory / "session")
        view = session.view()
        result.update(
            cost_spent=view["spent"],
            query_count=len(view["history"]),
            session_phase=view["phase"],
        )
        if view["phase"] == "completed":
            proof = session.verify()
            result.update(
                status="completed",
                error=None,
                science=view["evaluation"]["science"],
                decision=view["decision"],
                verification=proof,
                primary_family_brier=view["evaluation"]["science"]["family_brier"],
            )
    return result


def _verify_campaign(directory, result, spec, digest, item):
    if (
        result["protocol_hash"] != digest
        or result["block"] != item["block"]
        or result["policy"] != item["policy"]
    ):
        raise ValueError("Campaign allocation or protocol binding mismatch")
    if len(result["calls"]) > spec["max_model_calls"]:
        raise ValueError("Campaign exceeded its call budget")
    call_dirs = sorted((directory / "calls").glob("call-*"))
    if [c.name for c in call_dirs] != [
        f"call-{i:02d}" for i in range(1, len(result["calls"]) + 1)
    ]:
        raise ValueError("Unaccounted or missing model call attempts")
    responses = []
    for call, receipt in zip(call_dirs, result["calls"]):
        full = _read(call / "receipt.json")
        if {k: v for k, v in full.items() if k != "response"} != receipt:
            raise ValueError("Model call receipt changed")
        if (
            content_hash((call / "prompt.txt").read_text()) != receipt["prompt_hash"]
            or content_hash(_read(call / "schema.json")) != receipt["schema_hash"]
            or _read(call / "schema.json") != RESPONSE_SCHEMA
        ):
            raise ValueError("Frozen model prompt or schema changed")
        if (
            receipt.get("trace_sha256")
            and file_hash(call / "trace.jsonl") != receipt["trace_sha256"]
        ):
            raise ValueError("Model trace changed")
        if receipt["status"] == "succeeded":
            parsed = parse_events((call / "trace.jsonl").read_text())
            response = _read(call / "response.json")
            if (
                response != full["response"]
                or content_hash(response) != receipt["response_hash"]
                or response != json.loads(parsed["final_message"])
                or parsed["usage"] != receipt["usage"]
            ):
                raise ValueError("Response or usage differs from model trace")
            responses.append(response)
    if result["status"] == "completed":
        session = DemandSession(directory / "session")
        session.verify()
        final = session.view()
        if (
            final["evaluation"]["science"] != result["science"]
            or final["decision"] != result["decision"]
            or result["primary_family_brier"] != result["science"]["family_brier"]
        ):
            raise ValueError("Campaign evaluation changed")
        if (
            len(responses) != len(result["calls"])
            or len(responses) != len(final["history"]) + 1
        ):
            raise ValueError("Completed campaign calls do not match queries and stop")
        with session.transaction() as (c, state):
            events = [
                e["payload"]
                for e in session._events(c)
                if e["payload"]["type"] == "study_model_call"
            ]
        if len(events) != len(responses):
            raise ValueError("Campaign model-call commitments missing")
        view = dict(contract=final["contract"], history=[], remaining=spec["budget"])
        for i, (response, receipt, event, call) in enumerate(
            zip(responses, result["calls"], events, call_dirs)
        ):
            models, weights = infer(view)
            choices = available_actions(view) if i < spec["max_queries"] else {}
            context = scientist_context(view, spec, models, weights, choices)
            prompt = (
                spec["common_prompt"]
                + "\n\n"
                + spec["method_prompts"][item["policy"]]
                + "\n\nPUBLIC CONTEXT\n"
                + canonical_json(context)
            )
            if prompt != (call / "prompt.txt").read_text() or any(
                event[k] != receipt[k]
                for k in ("prompt_hash", "response_hash", "usage")
            ):
                raise ValueError(
                    "Model context or response commitment differs from campaign"
                )
            decision = validate_response(response, choices, context["stop_required"])
            if decision is not None:
                if i != len(responses) - 1 or decision != final["decision"]:
                    raise ValueError(
                        "Scientific stop differs from actual model response"
                    )
            else:
                actual = final["history"][i]
                action = choices[response["action_id"]]
                plan = measurement_plan(
                    view, action, models, weights, response["reason"]
                )
                if actual["action"] != action or actual["plan"] != plan:
                    raise ValueError(
                        "Query differs from actual model choice or common numerical plan"
                    )
                view["history"].append(actual)
                view["remaining"] -= actual["cost"]
        if (
            result["query_count"] > spec["max_queries"]
            or result["cost_spent"] > spec["budget"]
        ):
            raise ValueError("Campaign exceeded query or observation limits")
    elif result["primary_family_brier"] != 2:
        raise ValueError("Failed campaign does not receive its preregistered penalty")


def run_study(path: Path):
    path = Path(path).resolve()
    with (path / "study.lock").open("a") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise ValueError("Study supervisor already running") from exc
        spec, allocation, digest = load_study(path)
        blocks = {b["id"]: b for b in allocation["blocks"]}

        def run_one(item):
            directory = path / "campaigns" / (item["block"] + "-" + item["policy"])
            saved = directory / "result.json"
            if saved.is_file():
                outcome = _read(saved)
                _verify_campaign(directory, outcome, spec, digest, item)
            elif directory.exists():
                outcome = _recover_campaign(directory, item, digest)
                _write_new(saved, outcome)
                _verify_campaign(directory, outcome, spec, digest, item)
            else:
                directory.mkdir(parents=True)
                outcome = _campaign(
                    directory, spec, digest, blocks[item["block"]], item["policy"], path
                )
            return outcome

        results = []
        with ThreadPoolExecutor(max_workers=spec["concurrency"]) as pool:
            futures = [pool.submit(run_one, item) for item in spec["order"]]
            for future in futures:
                outcome = future.result()
                results.append(outcome)
                report = summarize(spec, results, digest)
                temp = path / "summary.pending.json"
                temp.write_text(json.dumps(report, indent=2) + "\n")
                temp.replace(path / "summary.json")
                yield outcome


def verify_study(path: Path) -> dict:
    spec, allocation, digest = load_study(path)
    path = Path(path).resolve()
    results = []
    for item in spec["order"]:
        directory = path / "campaigns" / (item["block"] + "-" + item["policy"])
        result = _read(directory / "result.json")
        _verify_campaign(directory, result, spec, digest, item)
        results.append(result)
    expected = summarize(spec, results, digest)
    if _read(path / "summary.json") != expected:
        raise ValueError("Published study summary differs from its campaigns")
    return dict(
        verified=True,
        protocol_hash=digest,
        campaigns=len(results),
        completed=sum(r["status"] == "completed" for r in results),
        scope="Frozen runtime/protocol/allocation, model call artifacts, native completed campaign replay and recomputed descriptive summary; not philosophical validity or immutable provider weights.",
    )
